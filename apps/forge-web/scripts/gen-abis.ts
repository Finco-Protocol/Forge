/**
 * Generates src/shared/abis.generated.ts from the W02 Forge-owned build
 * output (`forge build --profile forge`). `--check` fails when the committed
 * file drifts from the current W02 sources — the W03 app can never silently
 * diverge from the contracts it drives.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadArtifact } from "./artifacts";

const CONTRACTS: Array<[exportName: string, file: string, name?: string]> = [
  ["forgeBindingRegistryAbi", "ForgeBindingRegistry"],
  ["forgeLaunchAuthorizerAbi", "ForgeLaunchAuthorizer"],
  ["ponsV2LaunchFactoryAbi", "PonsV2LaunchFactory"],
  ["ponsV2LaunchDeployerAbi", "PonsV2LaunchDeployer"],
  ["ponsV2BondingCurveAbi", "PonsV2BondingCurve"],
  ["ponsV2MemeHookAbi", "PonsV2MemeHook"],
  ["ponsV2LaunchLockerAbi", "PonsV2LaunchLocker"],
  ["ponsV2LauncherTokenAbi", "PonsV2LauncherToken"],
  ["ponsV2FeeEscrowAbi", "PonsV2FeeEscrow"],
  ["ponsV2BuybackVaultAbi", "PonsV2BuybackVault"],
  ["forgeProtocolRevenueSplitterAbi", "ForgeProtocolRevenueSplitter"],
];

const target = path.resolve(import.meta.dirname, "..", "src", "shared", "abis.generated.ts");
let out =
  "// GENERATED by scripts/gen-abis.ts from `forge build --profile forge` (W02 sources).\n" +
  "// Do not edit by hand. CI runs `pnpm abi:check` to detect drift.\n\n";
for (const [exportName, file, name] of CONTRACTS) {
  const { abi } = loadArtifact(file, name);
  out += `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    /* missing */
  }
  if (current !== out) {
    console.error("ABI DRIFT: src/shared/abis.generated.ts does not match the W02 build output. Run `pnpm abi:gen`.");
    process.exit(1);
  }
  console.log("ABIs match the W02 build output.");
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
